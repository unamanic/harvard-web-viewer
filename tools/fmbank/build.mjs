#!/usr/bin/env node
/**
 * Builds src/audio/fm/bank.ts, the FM instrument bank the MIDI synthesizer
 * plays, from Freedoom's GENMIDI sources (BSD-3-Clause; see
 * src/audio/fm/licenses/Freedoom-BSD-3-Clause.txt).
 *
 * Usage:
 *   node tools/fmbank/build.mjs <freedoom>/lumps/genmidi
 *
 * The directory needs config.py (the instrument list) and instruments/
 * (the SBI files). config.py is read as text, not run: each entry is an
 * `Instrument('a.sbi', 'b.sbi', off1=-12, off2=-12, tune=+2, note=On3.Cs)`
 * call or `NullInstrument`, followed by a comment naming the General MIDI
 * instrument.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node tools/fmbank/build.mjs <freedoom>/lumps/genmidi");
  process.exit(1);
}
const out = new URL("../../src/audio/fm/bank.ts", import.meta.url);

/** Note constants of Freedoom's midi.py: On5 = octave base 0, ..., O0 = 60, O1 = 72 ... */
const OCTAVES = { On5: 0, On4: 12, On3: 24, On2: 36, On1: 48, O0: 60, O1: 72, O2: 84, O3: 96, O4: 108 };
const STEPS = { C: 0, Cs: 1, Db: 1, D: 2, Ds: 3, Eb: 3, E: 4, F: 5, Fs: 6, Gb: 6, G: 7, Gs: 8, Ab: 8, A: 9, As: 10, Bb: 10, B: 11 };

/** The 11 instrument bytes of an SBI file (after the 36-byte header), as hex. */
function sbi(name) {
  const d = readFileSync(join(dir, "instruments", name));
  if (d.subarray(0, 4).toString("latin1") !== "SBI\x1a") throw new Error(`${name}: not an SBI file`);
  return Buffer.from(d.subarray(36, 47)).toString("hex");
}

function parseList(text, listName) {
  const start = text.indexOf(`${listName} = [`);
  if (start < 0) throw new Error(`${listName} not found`);
  const end = text.indexOf("\n]", start);
  const body = text.slice(text.indexOf("[", start) + 1, end);
  // Split into entries: each starts at "Instrument(" or "NullInstrument" at the start of a line.
  const entries = [];
  for (const line of body.split("\n")) {
    const code = line.replace(/#.*$/, "").trim();
    const comment = (line.match(/#\s*(.*)$/)?.[1] ?? "").replace(/^#\d+\s*/, "").replace(/^TODO - #\d+\s*/, "").trim();
    if (/^(Instrument\(|NullInstrument)/.test(code)) entries.push({ code, comment });
    else if (code && entries.length) entries[entries.length - 1].code += " " + code;
  }
  return entries.map(({ code, comment }) => {
    if (code.startsWith("NullInstrument")) return { name: comment, files: ["dummy.sbi"], off: [0, 0], tune: 0, note: null };
    const args = code.slice(code.indexOf("(") + 1, code.lastIndexOf(")"));
    const files = [...args.matchAll(/['"]([^'"]+\.sbi)['"]/g)].map((m) => m[1]);
    const kw = Object.fromEntries([...args.matchAll(/(\w+)=([^,\s)]+)/g)].map((m) => [m[1], m[2]]));
    let note = null;
    if (kw.note) {
      const [oct, step] = kw.note.split(".");
      if (!(oct in OCTAVES) || !(step in STEPS)) throw new Error(`bad note ${kw.note}`);
      note = OCTAVES[oct] + STEPS[step];
    }
    return { name: comment, files, off: [Number(kw.off1 ?? 0), Number(kw.off2 ?? 0)], tune: Number(kw.tune ?? 0), note };
  });
}

const config = readFileSync(join(dir, "config.py"), "utf8");
const melodic = parseList(config, "INSTRUMENTS");
const percussion = parseList(config, "PERCUSSION");
if (melodic.length !== 128 || percussion.length !== 47) throw new Error(`expected 128 + 47 instruments, got ${melodic.length} + ${percussion.length}`);

const row = (i) => {
  const voices = i.files.map((f, k) => `"${sbi(f)}", ${i.off[k]}`).join(", ");
  return `  [${JSON.stringify(i.name)}, ${i.note ?? "null"}, ${i.tune}, ${voices}],`;
};

const ts = `/**
 * FM instrument bank: General MIDI instruments 1-128 and percussion keys
 * 35-81 for a two-operator FM chip (YM3812 / OPL2), in the layout of the
 * DMX "GENMIDI" bank.
 *
 * GENERATED by tools/fmbank/build.mjs from Freedoom's GENMIDI sources
 * (lumps/genmidi, commit 8c0a4bc of 2023-06-24). Do not edit by hand.
 *
 * Copyright © 2001-2024 Contributors to the Freedoom project. All rights
 * reserved. BSD-3-Clause: see licenses/Freedoom-BSD-3-Clause.txt.
 *
 * Each row: [name, fixed note or null, fine tune, voice 1 bytes, voice 1
 * note offset, (voice 2 bytes, voice 2 note offset)]. Voice bytes are the
 * 11 bytes of an SBI instrument: modulator and carrier 0x20 (AM, vibrato,
 * sustain, KSR, multiple), modulator and carrier 0x40 (KSL, level),
 * modulator and carrier 0x60 (attack, decay), modulator and carrier 0x80
 * (sustain level, release), modulator and carrier 0xE0 (waveform), and
 * 0xC0 (feedback, connection). Notes and offsets count as the DMX player
 * does (bank.ts users: synth.ts).
 */
export type BankRow = readonly [string, number | null, number, string, number, ...([] | [string, number])];

/** General MIDI programs 0-127. */
export const MELODIC: readonly BankRow[] = [
${melodic.map(row).join("\n")}
];

/** Percussion keys 35-81 (index = key - 35). */
export const PERCUSSION: readonly BankRow[] = [
${percussion.map(row).join("\n")}
];
`;
writeFileSync(out, ts);
console.log(`wrote ${out.pathname}: ${melodic.length} melodic, ${percussion.length} percussion`);
