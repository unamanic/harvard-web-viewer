#!/usr/bin/env node
/**
 * Generate src/fonts/stroke/hersheyData.ts, the glyph data of the viewer's
 * own stroke font clones (docs/RENDERER_TASKS.md task 7d-1), from the
 * public-domain Hershey fonts in James Hurt's .jhf format.
 *
 * Usage, from the repository root:
 *
 *   node scripts/gen-stroke-fonts.mjs path/to/jhf-directory
 *
 * The directory must hold the .jhf files listed in SETS below, as
 * distributed in kamalmostafa/hershey-fonts tag hershey-fonts-0.1 (see
 * src/fonts/stroke/README.md for the exact URLs). Only Hershey data is read;
 * nothing comes from the Harvard Graphics font files.
 *
 * Each .jhf record is: glyph number (5 columns), vertex count (3 columns),
 * then count pairs of characters, each coordinate being its character code
 * minus 'R'. The first pair is the left and right side bearing; " R" lifts
 * the pen. The ASCII-ordered files hold 96 records for codes 32 to 127.
 * The generated module keeps each glyph as its pair string (left/right pair
 * first), which is compact and decoded at run time by strokeFont.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "src/fonts/stroke/hersheyData.ts");

/** Hershey sets used by the clones: id → file and description. */
const SETS = [
  ["romanSimplex", "rowmans.jhf", "Roman Simplex (single-stroke sans serif)"],
  ["romanDuplex", "rowmand.jhf", "Roman Duplex (double-stroke sans serif)"],
  ["romanComplex", "timesr.jhf", "Roman Complex (single-stroke serif, Times-like)"],
  ["romanTriplex", "rowmant.jhf", "Roman Triplex (triple-stroke serif)"],
  ["scriptSimplex", "scripts.jhf", "Script Simplex (single-stroke script)"],
  ["scriptComplex", "scriptc.jhf", "Script Complex (double-stroke script)"],
  ["gothicEnglish", "gothiceng.jhf", "Gothic English (blackletter)"],
];

const GLYPHS_PER_SET = 96;

/**
 * Known errors in the distributed data, fixed here: [file, character, wrong
 * side bearings, right side bearings]. rowmant.jhf gives "J" (Hershey 3010)
 * a zero width, "JJ"; timesrb.jhf carries the same Triplex J with "JZ".
 */
const FIXES = [["rowmant.jhf", "J", "JJ", "JZ"]];

/** Parse one .jhf file into its glyph pair strings, tolerating wrapped lines. */
function parseJhf(text, file) {
  const chars = text.replace(/\r/g, "");
  const glyphs = [];
  let i = 0;
  const take = (n) => {
    let s = "";
    while (s.length < n) {
      if (i >= chars.length) throw new Error(`${file}: unexpected end of data`);
      const c = chars[i++];
      if (c !== "\n") s += c;
    }
    return s;
  };
  while (i < chars.length) {
    while (i < chars.length && chars[i] === "\n") i++;
    if (i >= chars.length) break;
    const head = take(8);
    const count = Number.parseInt(head.slice(5, 8), 10);
    if (!Number.isFinite(count) || count < 1) throw new Error(`${file}: bad record header "${head}"`);
    const pairs = take(count * 2);
    if (pairs[0] === " " || pairs[1] === " ") throw new Error(`${file}: glyph ${glyphs.length} has no side bearings`);
    glyphs.push(pairs);
  }
  if (glyphs.length !== GLYPHS_PER_SET) throw new Error(`${file}: expected ${GLYPHS_PER_SET} glyphs, found ${glyphs.length}`);
  return glyphs;
}

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node scripts/gen-stroke-fonts.mjs path/to/jhf-directory");
  process.exit(1);
}

let body = "";
for (const [id, file, description] of SETS) {
  const glyphs = parseJhf(readFileSync(join(dir, file), "latin1"), file);
  for (const [fixFile, ch, wrong, right] of FIXES) {
    if (fixFile !== file) continue;
    const at = ch.charCodeAt(0) - 32;
    if (!glyphs[at].startsWith(wrong)) throw new Error(`${file}: fix for "${ch}" no longer applies`);
    glyphs[at] = right + glyphs[at].slice(2);
  }
  body += `  /** Hershey ${description}, from ${file}. */\n`;
  body += `  ${id}: [\n${glyphs.map((g) => `    ${JSON.stringify(g)},`).join("\n")}\n  ],\n`;
}

const source = `/**
 * Hershey font glyph data for the stroke font clones (task 7d-1).
 * GENERATED by scripts/gen-stroke-fonts.mjs: do not edit by hand.
 * Provenance and licence: see README.md in this folder.
 *
 * The Hershey Fonts were originally created by Dr. A. V. Hershey while
 * working at the U. S. National Bureau of Standards.
 * The format of the Font data in this distribution was originally created by
 * James Hurt, Cognition, Inc., 900 Technology Park Drive, Billerica, MA 01821
 * (mit-eddie!ci-dandelion!hurt).
 *
 * Each set lists 96 glyphs for character codes 32 to 127. A glyph is a
 * string of coordinate pairs, each coordinate being its character code minus
 * 'R' (82): the first pair is the left and right side bearing, then the
 * stroke vertices, with " R" lifting the pen. y grows downwards and the
 * baseline is at y = 9.
 */

export type HersheySetId =
${SETS.map(([id]) => `  | "${id}"`).join("\n")};

export const HERSHEY_SETS: Readonly<Record<HersheySetId, readonly string[]>> = {
${body}};
`;

writeFileSync(output, source);
console.log(`wrote ${output} (${source.length} bytes)`);
